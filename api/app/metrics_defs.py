"""Prometheus metric definitions for RAHBAR (Track A).

Centralized Prometheus metrics definitions for API request counts, latencies,
cache performance, honest abstentions, validation fallbacks, and token usage.
"""

from __future__ import annotations

from prometheus_client import Counter, Histogram

# HTTP Request metrics (reused from starter kit)
REQUESTS = Counter(
    "rahbar_requests_total",
    "HTTP requests by path and status code",
    ["path", "status"],
)

LATENCY = Histogram(
    "rahbar_request_seconds",
    "HTTP request latency in seconds",
    ["path"],
    buckets=(0.05, 0.1, 0.25, 0.5, 1.0, 2.0, 5.0, 10.0, 30.0, 60.0),
)

# Pipeline component latencies
RETRIEVAL_LATENCY = Histogram(
    "rahbar_retrieval_latency_seconds",
    "Vector store retrieval latency in seconds",
    buckets=(0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 2.0, 5.0),
)

GENERATION_LATENCY = Histogram(
    "rahbar_generation_latency_seconds",
    "LLM generation latency in seconds",
    buckets=(0.1, 0.25, 0.5, 1.0, 2.0, 5.0, 10.0, 30.0),
)

# Semantic cache metrics
CACHE_HITS = Counter(
    "rahbar_cache_hits_total",
    "Total number of semantic cache hits",
)

CACHE_MISSES = Counter(
    "rahbar_cache_misses_total",
    "Total number of semantic cache misses",
)

# Grounding & safety metrics
ABSTENTIONS = Counter(
    "rahbar_abstentions_total",
    "Total number of queries where the system honestly abstained from answering",
)

FALLBACKS = Counter(
    "rahbar_fallbacks_total",
    "Total number of fallback generations triggered due to validation failure",
)

# Token accounting
TOKENS_IN = Counter(
    "rahbar_tokens_in_total",
    "Total number of input/prompt tokens sent to the LLM",
)

TOKENS_OUT = Counter(
    "rahbar_tokens_out_total",
    "Total number of output/completion tokens generated by the LLM",
)

